test("identified, unidentified, strict, and switched MCP saves preserve compatibility", async () => {
    const firstExternalId = uniqueValue("actor:test:session-a");
    const secondExternalId = uniqueValue("actor:test:session-b");
    const unidentifiedText = uniqueValue("unidentified-save");
    const identifiedText = uniqueValue("identified-save");
    const switchedText = uniqueValue("switched-save");
    const connection = await connectTestClient();
    const savedIds = [];
    const actorIds = [];

    try {
        const unidentified = textResult(await connection.client.callTool({
            name: "save_context",
            arguments: { text: unidentifiedText },
        }));
        savedIds.push(unidentified.saved.id);
        assert.equal(unidentified.saved.actor, null);
        assert.equal(unidentified.warning.code, "ACTOR_NOT_IDENTIFIED");

        const firstIdentity = textResult(await connection.client.callTool({
            name: "identify_actor",
            arguments: { external_id: firstExternalId, name: "Session A", kind: "ai" },
        }));
        actorIds.push(firstIdentity.identified.actor.id);
        const identified = textResult(await connection.client.callTool({
            name: "save_context",
            arguments: { text: identifiedText },
        }));
        savedIds.push(identified.saved.id);
        assert.equal(identified.saved.actor.external_id, firstExternalId);
        assert.equal(identified.warning, undefined);

        const secondIdentity = textResult(await connection.client.callTool({
            name: "identify_actor",
            arguments: { external_id: secondExternalId, name: "Session B", kind: "human" },
        }));
        actorIds.push(secondIdentity.identified.actor.id);
        const switched = textResult(await connection.client.callTool({
            name: "save_context",
            arguments: { text: switchedText },
        }));
        savedIds.push(switched.saved.id);
        assert.equal(switched.saved.actor.external_id, secondExternalId);

        process.env.REQUIRE_ACTOR_IDENTIFICATION = "true";
        assert.equal(requireActorIdentificationEnabled(), true);
        const strictConnection = await connectTestClient();
        try {
            const strictResult = await strictConnection.client.callTool({
                name: "save_context",
                arguments: { text: uniqueValue("strict-rejected") },
            });
            assert.equal(strictResult.isError, true);
            assert.equal(textResult(strictResult).error.code, "ACTOR_IDENTIFICATION_REQUIRED");
        } finally {
            await strictConnection.close();
        }
    } finally {
        delete process.env.REQUIRE_ACTOR_IDENTIFICATION;
        await connection.close();
        if (savedIds.length > 0) await db.query("DELETE FROM contexts WHERE id = ANY($1::bigint[])", [savedIds]);
        if (actorIds.length > 0) await db.query("DELETE FROM actors WHERE id = ANY($1::bigint[])", [actorIds]);
    }
});

test("text, semantic, and recent queries filter inside the actor boundary", async () => {
    const firstExternalId = uniqueValue("actor:test:filter-a");
    const secondExternalId = uniqueValue("actor:test:filter-b");
    const marker = uniqueValue("actor-filter-marker");
    const firstActor = await identifyActor({ external_id: firstExternalId, name: "Filter A" });
    const secondActor = await identifyActor({ external_id: secondExternalId, name: "Filter B" });
    const firstContext = await saveContext(marker, [], "filter test", firstActor.actor.id);
    const secondContext = await saveContext(marker, [], "filter test", secondActor.actor.id);

    try {
        await db.query(
            `INSERT INTO embeddings (context_id, model, vector, created_at, updated_at)
             VALUES ($1, 'actor-test-model', '[1,0]', NOW(), NOW()),
                    ($2, 'actor-test-model', '[1,0]', NOW(), NOW())
             ON CONFLICT (context_id) DO UPDATE SET model = EXCLUDED.model, vector = EXCLUDED.vector`,
            [firstContext.id, secondContext.id],
        );

        const textResults = await searchContext(marker, 20, "low", firstExternalId);
        assert.deepEqual(textResults.map((context) => context.id), [firstContext.id]);

        const semanticResults = await searchContextByVector(
            marker,
            20,
            "low",
            secondExternalId,
            async () => ({ generated: true, model: "actor-test-model", vector: [1, 0] }),
        );
        assert.deepEqual(semanticResults.map((context) => context.id), [secondContext.id]);

        const recentResults = await listRecentContext(20, firstExternalId);
        assert.ok(recentResults.some((context) => context.id === firstContext.id));
        assert.ok(recentResults.every((context) => context.actor?.external_id === firstExternalId));
    } finally {
        await db.query("DELETE FROM contexts WHERE id = ANY($1::bigint[])", [[firstContext.id, secondContext.id]]);
        await db.query("DELETE FROM actors WHERE id = ANY($1::bigint[])", [[firstActor.actor.id, secondActor.actor.id]]);
    }
});

test("administrative context projections and metadata include actors", async () => {
    const externalId = uniqueValue("actor:test:admin");
    const identified = await identifyActor({ external_id: externalId, name: "Admin Projection" });
    const saved = await saveContext(uniqueValue("admin-projection"), [], undefined, identified.actor.id);

    try {
        const updated = await updateContext(saved.id, "updated actor projection");
        assert.equal(updated.actor.external_id, externalId);

        const metadata = await getDatabaseMetadata();
        assert.ok(metadata.actor_count >= 1);
        assert.ok(metadata.tables.actors.bytes > 0);

        const deleted = await deleteContext(saved.id);
        assert.equal(deleted.actor.external_id, externalId);
    } finally {
        await db.query("DELETE FROM contexts WHERE id = $1", [saved.id]);
        await db.query("DELETE FROM actors WHERE id = $1", [identified.actor.id]);
    }
});

test("user profile returns only explicitly tagged contexts", async () => {
    const marker = uniqueValue("profile-tag");
    const profileContext = await saveContext(`${marker} curated`, ["profile"]);
    const ordinaryContext = await saveContext(`${marker} ordinary`, ["history"]);

    try {
        const profile = await getUserProfile();
        assert.equal(profile.tag, "profile");
        assert.ok(profile.results.some((context) => context.id === profileContext.id));
        assert.ok(profile.results.every((context) => context.tags.includes("profile")));
        assert.ok(profile.results.every((context) => context.id !== ordinaryContext.id));
    } finally {
        await db.query("DELETE FROM contexts WHERE id = ANY($1::bigint[])", [[profileContext.id, ordinaryContext.id]]);
    }
});

test("built MCP schemas expose actor identification and stable actor filters", async () => {
    const connection = await connectTestClient();

    try {
        const { tools } = await connection.client.listTools();
        const byName = new Map(tools.map((tool) => [tool.name, tool]));
        const identifySchema = byName.get("identify_actor")?.inputSchema;
        const searchSchema = byName.get("search_context")?.inputSchema;
        const recentSchema = byName.get("list_recent_context")?.inputSchema;
        const saveSchema = byName.get("save_context")?.inputSchema;

        assert.deepEqual(identifySchema.required, ["name"]);
        assert.ok(identifySchema.properties.external_id);
        assert.ok(searchSchema.properties.actor_external_id);
        assert.ok(recentSchema.properties.actor_external_id);
        assert.deepEqual(Object.keys(saveSchema.properties).sort(), ["source", "tags", "text"]);
    } finally {
        await connection.close();
    }
});

