function uniqueValue(prefix) {
    return `${prefix}-${process.pid}-${Date.now()}-${Math.random().toString(16).slice(2)}`;
}

async function connectTestClient() {
    const server = createServer();
    const client = new Client({ name: "actor-attribution-test", version: "1.0.0" });
    const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();

    await Promise.all([
        server.connect(serverTransport),
        client.connect(clientTransport),
    ]);

    return {
        client,
        server,
        async close() {
            await client.close();
            await server.close();
        },
    };
}

function textResult(result) {
    const item = result.content.find((content) => content.type === "text");
    assert.ok(item);
    return JSON.parse(item.text);
}

test("versioned migrations upgrade a legacy schema without attributing existing rows", async () => {
    const schema = uniqueValue("actor_migration").replaceAll("-", "_");
    const adminPool = new pg.Pool();
    await adminPool.query(`CREATE SCHEMA ${schema}`);
    const isolatedPool = new pg.Pool({ options: `-c search_path=${schema}` });

    try {
        await isolatedPool.query(`
            CREATE TABLE contexts (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind TEXT NOT NULL DEFAULT 'note',
                content TEXT NOT NULL,
                source TEXT,
                tags TEXT[],
                created_at TIMESTAMPTZ NOT NULL,
                updated_at TIMESTAMPTZ NOT NULL
            );
            CREATE TABLE embeddings (
                context_id BIGINT PRIMARY KEY REFERENCES contexts(id) ON DELETE CASCADE,
                vector TEXT
            );
            INSERT INTO contexts (content, created_at, updated_at)
            VALUES ('legacy actor migration row', NOW(), NOW());
        `);

        await runDatabaseMigrations(isolatedPool);

        const legacy = await isolatedPool.query("SELECT actor_id FROM contexts");
        const applied = await isolatedPool.query("SELECT version FROM schema_migrations ORDER BY version");
        assert.equal(legacy.rows[0].actor_id, null);
        assert.deepEqual(applied.rows.map((row) => row.version), [1, 2]);
    } finally {
        await isolatedPool.end();
        await adminPool.query(`DROP SCHEMA ${schema} CASCADE`);
        await adminPool.end();
    }
});

test("actor resolution is concurrency-safe and never merges name-only actors", async () => {
    await initializeDatabase();
    const externalId = uniqueValue("actor:test:concurrent");
    const [left, right] = await Promise.all([
        identifyActor({ external_id: externalId, name: "Concurrent Actor", kind: "ai" }),
        identifyActor({ external_id: externalId, name: "Ignored Duplicate Name", kind: "ai" }),
    ]);
    const firstNameOnly = await identifyActor({ name: "Same Display Name" });
    const secondNameOnly = await identifyActor({ name: "Same Display Name" });

    try {
        assert.equal(left.actor.id, right.actor.id);
        assert.equal(Number(left.created) + Number(right.created), 1);
        assert.notEqual(firstNameOnly.actor.id, secondNameOnly.actor.id);
    } finally {
        await db.query("DELETE FROM actors WHERE id = ANY($1::bigint[])", [[left.actor.id, firstNameOnly.actor.id, secondNameOnly.actor.id]]);
    }
});

